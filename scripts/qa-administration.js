async (page) => {
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  const report = [];
  const base = 'file:///home/fjeanne/dev/projets/glimlink/maquette.html';
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base + '#/admin/home');
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  for (const width of [1366, 390, 320]) {
    await page.setViewportSize({ width, height: 900 });
    await page.goto(base + '#/admin/home');
    await page.getByRole('heading', { name: 'Votre réseau, bien organisé.' }).waitFor();
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Débordement accueil ' + width);
    await page.getByRole('button', { name: /^Choisir l’espace de démonstration/ }).click();
    assert(await page.getByRole('menuitemradio', { name: 'Espace administrateur', exact: true }).getAttribute('aria-checked') === 'true', 'Rôle admin');
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: 'Ajouter une formation', exact: true }).click();
    const dialog = page.getByRole('dialog');
    const title = 'Formation test ' + width;
    await dialog.getByLabel('Nom de la formation').fill(title);
    await dialog.getByLabel('Début d’application').fill('2026-10-01');
    await dialog.getByLabel('Fin d’application').fill('2027-07-01');
    await dialog.getByText('Lundi', { exact: true }).click();
    await dialog.getByLabel('Nom de la compétence').fill('Gestion de projet');
    await dialog.getByRole('button', { name: 'Ajouter la compétence', exact: true }).click();
    assert(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth), 'Débordement formation ' + width);
    if (width !== 320) await page.screenshot({ path: '/home/fjeanne/dev/projets/glimlink/docs/screenshots/admin-formation-' + width + '.png' });
    await dialog.getByRole('button', { name: 'Enregistrer le calendrier' }).click();
    await page.goto(base + '#/admin/calendars');
    await page.reload();
    const training = await page.evaluate(title => JSON.parse(localStorage.getItem('glimlink-prototype-v1')).calendars.find(item => item.title === title), title);
    assert(training.courseDays.includes('Lundi') && training.learningSkills[0].name === 'Gestion de projet', 'Persistance formation');
    await page.goto(base + '#/adviser/students');
    await page.getByRole('button', { name: 'Importer un CV' }).click();
    await page.getByLabel('Prénom du talent').fill('Camille');
    await page.getByRole('button', { name: 'Créer le brouillon' }).click();
    await dialog.getByRole('combobox', { name: 'Choisir : Formation / promotion', exact: true }).click();
    await page.getByRole('option', { name: title, exact: true }).click();
    assert((await dialog.locator('.inherited-calendar').textContent()).includes('En cours'), 'Rattachement formation conseiller');
    await page.keyboard.press('Escape');
    await page.goto(base + '#/adviser/home');
    await page.locator('.training-row').first().click();
    await page.getByRole('heading', { name: 'Le rythme de vos formations.' }).waitFor();
    assert(await page.getByRole('dialog').count() === 0 && await page.getByRole('button', { name: 'Modifier la formation' }).count() === 0, 'Consultation conseiller');
    await page.goto(base + '#/admin/users');
    await page.getByRole('button', { name: 'Ajouter un utilisateur' }).click();
    await dialog.getByLabel('Prénom', { exact: true }).fill('Lou');
    await dialog.getByLabel('Nom', { exact: true }).fill('Martin ' + width);
    await dialog.getByLabel('E-mail', { exact: true }).fill('lou' + width + '@example.com');
    await dialog.getByLabel('Téléphone', { exact: true }).fill('04 00 00 00 00');
    await dialog.getByLabel('Adresse complète').fill('1 rue du Centre, 34000 Montpellier');
    assert(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth), 'Débordement utilisateur ' + width);
    await dialog.getByRole('button', { name: 'Enregistrer l’utilisateur' }).click();
    await page.reload();
    assert(await page.locator('.admin-record').filter({ hasText: 'lou' + width + '@example.com' }).count() === 1, 'Persistance utilisateur');
    await page.goto(base + '#/admin/companies');
    await page.getByRole('button', { name: 'Ajouter une entreprise' }).click();
    for (const [label, value] of [['Nom de l’entreprise', 'Entreprise test ' + width], ['Secteur d’activité', 'Services'], ['Contact principal', 'Lou Martin'], ['Fonction du contact', 'Direction'], ['Ville', 'Montpellier'], ['E-mail', 'entreprise' + width + '@example.com'], ['Téléphone', '04 00 00 00 01'], ['Adresse complète', '2 rue du Centre, 34000 Montpellier']]) await dialog.getByLabel(label, { exact: true }).fill(value);
    assert(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth), 'Débordement entreprise ' + width);
    await dialog.getByRole('button', { name: 'Enregistrer l’entreprise' }).click();
    await page.reload();
    const record = page.locator('.admin-record').filter({ hasText: 'Entreprise test ' + width });
    assert((await record.textContent()).includes('04 00 00 00 01') && (await record.textContent()).includes('Activation à effectuer'), 'Persistance entreprise');
    await page.goto(base + '#/adviser/companies');
    assert((await page.locator('main').textContent()).includes('Entreprise test ' + width), 'Partenaire visible conseiller');
    await page.goto(base + '#/admin/home');
    if (width !== 320) await page.screenshot({ path: '/home/fjeanne/dev/projets/glimlink/docs/screenshots/admin-home-' + width + '.png', fullPage: true });
    report.push({ width, status: 'pass', journeys: 'trois ajouts, rechargement, rattachement candidat, consultation conseiller et débordements' });
  }
  assert(errors.length === 0, 'Erreurs JavaScript : ' + errors.join(', '));
  await page.evaluate(() => localStorage.clear());
  return report;
}
